#!/usr/bin/env python3
import argparse
import json
import re
from pathlib import Path


def acceptable_cpp(name: str) -> str:
    name = name.lower()
    name = re.sub(r"[^0-9a-zA-Z_]", "_", name)
    if not name or name[0].isdigit():
        name = f"_{name}"
    return name


def generate(units_json: Path, header_path: Path, impl_path: Path, idl_path: Path) -> None:
    units = json.loads(units_json.read_text(encoding="utf-8"))

    header = [
        "#pragma once",
        "",
        "#include <LibGC/Ptr.h>",
        "#include <LibJS/Forward.h>",
        "#include <LibWeb/Forward.h>",
        "#include <LibWeb/WebIDL/Types.h>",
        "",
        "// Generated by scripts/generate_css_numeric_factory_methods.py",
        "namespace Web::CSS {",
        "",
        "GC::Ref<CSSUnitValue> number(JS::VM&, WebIDL::Double value);",
        "GC::Ref<CSSUnitValue> percent(JS::VM&, WebIDL::Double value);",
    ]

    impl = [
        "#include <AK/FlyString.h>",
        "#include <LibJS/Runtime/VM.h>",
        "#include <LibWeb/CSS/CSSUnitValue.h>",
        "#include <LibWeb/CSS/GeneratedCSSNumericFactoryMethods.h>",
        "",
        "// Generated by scripts/generate_css_numeric_factory_methods.py",
        "namespace Web::CSS {",
        "",
        "inline GC::Ref<CSSUnitValue> numeric_factory(JS::VM& vm, WebIDL::Double value, FlyString unit)",
        "{",
        "    return CSSUnitValue::create(*vm.current_realm(), value, move(unit));",
        "}",
        "",
        "GC::Ref<CSSUnitValue> number(JS::VM& vm, WebIDL::Double value)",
        "{",
        "    return numeric_factory(vm, value, \"number\"_fly_string);",
        "}",
        "",
        "GC::Ref<CSSUnitValue> percent(JS::VM& vm, WebIDL::Double value)",
        "{",
        "    return numeric_factory(vm, value, \"percent\"_fly_string);",
        "}",
    ]

    idl = [
        "partial namespace CSS {",
        "    CSSUnitValue number(double value);",
        "    CSSUnitValue percent(double value);",
        "",
    ]

    for dimension_name, dimension in units.items():
        dimension_cpp = acceptable_cpp(dimension_name)
        header.extend(["", f"// {dimension_cpp}"])
        impl.extend(["", f"// {dimension_cpp}"])
        idl.append(f"    // {dimension_cpp}")
        for unit_name in dimension.keys():
            cpp_name = acceptable_cpp(unit_name)
            header.append(f"GC::Ref<CSSUnitValue> {cpp_name}(JS::VM&, WebIDL::Double value);")
            impl.extend([
                "",
                f"GC::Ref<CSSUnitValue> {cpp_name}(JS::VM& vm, WebIDL::Double value)",
                "{",
                f"    return numeric_factory(vm, value, \"{unit_name}\"_fly_string);",
                "}",
            ])
            idl.append(f"    [ImplementedAs={cpp_name}] CSSUnitValue {unit_name}(double value);")

    header.extend(["", "}"])
    impl.extend(["", "}"])
    idl.extend(["", "};"])

    header_path.write_text("\n".join(header) + "\n", encoding="utf-8")
    impl_path.write_text("\n".join(impl) + "\n", encoding="utf-8")
    idl_path.write_text("\n".join(idl) + "\n", encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--json-path", required=True)
    parser.add_argument("--generated-header-path", required=True)
    parser.add_argument("--generated-implementation-path", required=True)
    parser.add_argument("--generated-idl-path", required=True)
    args = parser.parse_args()

    generate(
        Path(args.json_path),
        Path(args.generated_header_path),
        Path(args.generated_implementation_path),
        Path(args.generated_idl_path),
    )


if __name__ == "__main__":
    main()
