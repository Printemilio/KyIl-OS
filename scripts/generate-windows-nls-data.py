"""Freeze semantic NLS reference data, never Windows code or DLLs.

Run explicitly on Windows when updating the checked-in profile. Normal guest
builds consume the generated tables and have no host NLS/runtime dependency.
Only en-US/invariant profiles are installed. Supplementary casing/linguistic
sort weights are separate contracts and are not inferred from these tables.
"""
import ctypes as C, json, pathlib, sys, hashlib
root=pathlib.Path(__file__).resolve().parents[1]
k=C.WinDLL('kernel32',use_last_error=True)
ctype=k.GetStringTypeW;ctype.argtypes=[C.c_uint,C.POINTER(C.c_ushort),C.c_int,C.POINTER(C.c_ushort)]
mapping=k.LCMapStringW;mapping.argtypes=[C.c_uint,C.c_uint,C.POINTER(C.c_ushort),C.c_int,C.POINTER(C.c_ushort),C.c_int]
info=k.GetLocaleInfoW;info.argtypes=[C.c_uint,C.c_uint,C.POINTER(C.c_ushort),C.c_int]
lines=['/* Semantic reference tables, generated by scripts/generate-windows-nls-data.py. */',
       'static const struct {uint16_t first,last,value[3];} nls_types[]={']
start=0;previous=None;rows=0
for code in range(65536):
    source=C.c_ushort(code);out=C.c_ushort();values=[]
    for kind in (1,2,4):
        if not ctype(kind,C.byref(source),1,C.byref(out)):raise RuntimeError(('ctype',code,C.get_last_error()))
        values.append(out.value)
    values=tuple(values)
    if previous is not None and values!=previous:
        lines.append('{%d,%d,{%s}},'%(start,code-1,','.join(map(str,previous))));start=code;rows+=1
    previous=values
lines.append('{%d,65535,{%s}},};'%(start,','.join(map(str,previous))))
lines.append('static const struct {uint16_t source,lower,upper;} nls_case[]={')
for code in range(65536):
    source=C.c_ushort(code);results=[]
    for flag in (0x100,0x200):
        out=(C.c_ushort*8)();n=mapping(0x7f,flag,C.byref(source),1,out,8)
        if n!=1:raise RuntimeError(('non-simple case',code,flag,n))
        results.append(out[0])
    if any(value!=code for value in results):lines.append('{%d,%d,%d},'%(code,*results))
lines.append('};')
lines.append('static const struct {uint32_t locale,type,number,has_number;const uint16_t *text;unsigned length;} nls_locales[]={')
types=list(range(1,0x100))+list(range(0x1000,0x1020))+list(range(0x2000,0x2020))
for locale in (0x7f,0x409):
    for kind in types:
        out=(C.c_ushort*512)();n=info(locale,kind|0x80000000,out,512)
        if not n:continue
        number=(C.c_ushort*2)();has=info(locale,kind|0xa0000000,number,2)
        value=number[0]|(number[1]<<16) if has else 0
        text=','.join(str(out[i]) for i in range(n))
        lines.append('{%d,%d,%d,%d,(const uint16_t[]){%s},%d},'%(locale,kind,value,1 if has else 0,text,n))
lines.append('};')
data='\n'.join(lines)+'\n'
target=root/'userspace/windows/nls_data.h';target.write_text(data,encoding='utf8')
provenance={'source':'Public Windows NLS function results; data only, no DLL/code included','host':str(sys.getwindowsversion()),
 'locales':['invariant','en-US'],'ctype':'BMP CT_CTYPE1/2/3, per UTF-16 code unit','case':'invariant simple BMP upper/lower',
 'sha256':hashlib.sha256(data.encode()).hexdigest()}
target.with_suffix('.json').write_text(json.dumps(provenance,indent=2)+'\n',encoding='utf8')
print('Generated NLS semantic data:',provenance)
