"""Generate the KyIlOS system UI assets from figma_assets/Inter-Regular.ttf.

Outputs (all generated, never edited by hand):

  kernel/src/ui_font_inter.c        LVGL fonts lv_font_inter_{12,14,16,20}
  kernel/include/unos/ui_fonts.h    their declarations
  kernel/src/ui_brand_masks.c       8-bit alpha masks: hexagon icons and the
                                    "KyIl<hex>S" desktop wordmark
  kernel/include/unos/ui_brand.h    their declarations

Masks carry coverage only. The kernel colours them with the active theme at
draw time, so the same asset serves the dark and the light theme.

    python scripts/generate_kyil_ui_assets.py
"""
from __future__ import annotations

import math
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
FONT_PATH = ROOT / "figma_assets" / "Inter-Regular.ttf"
KERNEL_SRC = ROOT / "kernel" / "src"
KERNEL_INC = ROOT / "kernel" / "include" / "unos"

SEMIBOLD_PATH = ROOT / "userspace" / "suchu" / "assets" / "fonts" / "Inter-SemiBold.ttf"
FONT_SIZES = (12, 14, 16, 20)
# (face file, LVGL symbol infix, size): the weights the shell needs.
FONTS = [(FONT_PATH, "", size) for size in FONT_SIZES] + [(SEMIBOLD_PATH, "semibold_", 14)]
# ASCII, Latin-1 (French accents) and the typographic marks the UI uses.
EXTRA_CODEPOINTS = (0x2013, 0x2014, 0x2018, 0x2019, 0x201C, 0x201D, 0x2022, 0x2026, 0x2190,
                    0x2192, 0x2191, 0x2193, 0x203A, 0x2039, 0x00D7)
SUPERSAMPLE = 4


def codepoints() -> list[int]:
    points = list(range(0x20, 0x7F)) + list(range(0xA0, 0x100)) + list(EXTRA_CODEPOINTS)
    return sorted(set(points))


def c_bytes(data: bytes, indent: str = "    ", per_line: int = 16) -> str:
    lines = []
    for i in range(0, len(data), per_line):
        lines.append(indent + ", ".join(f"0x{b:02x}" for b in data[i:i + per_line]) + ",")
    return "\n".join(lines)


def render_glyph(font: ImageFont.FreeTypeFont, char: str):
    """Tight 8-bit coverage box of a glyph, placed against its baseline."""
    mask, offset = font.getmask2(char, mode="L", anchor="ls")
    width, height = mask.size
    if width == 0 or height == 0:
        return b"", 0, 0, 0, 0
    image = Image.frombytes("L", (width, height), bytes(mask))
    box = image.getbbox()
    if box is None:
        return b"", 0, 0, 0, 0
    image = image.crop(box)
    left = offset[0] + box[0]
    top = offset[1] + box[1]  # relative to the baseline, negative above it
    box_w, box_h = image.size
    ofs_y = -(top + box_h)    # LVGL: bottom of the box above the baseline
    return image.tobytes(), box_w, box_h, left, ofs_y


def generate_font(path: Path, weight: str, size: int) -> str:
    font = ImageFont.truetype(str(path), size)
    ascent, descent = font.getmetrics()
    points = codepoints()
    bitmap = bytearray()
    glyphs = ["    {.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0} /* id = 0 reserved */"]
    for point in points:
        char = chr(point)
        data, box_w, box_h, ofs_x, ofs_y = render_glyph(font, char)
        advance = round(font.getlength(char) * 16)
        glyphs.append(
            f"    {{.bitmap_index = {len(bitmap)}, .adv_w = {advance}, .box_w = {box_w}, "
            f".box_h = {box_h}, .ofs_x = {ofs_x}, .ofs_y = {ofs_y}}} /* U+{point:04X} */")
        bitmap += data

    ascii_points = [p for p in points if p < 0x7F]
    other = [p for p in points if p >= 0x7F]
    base = other[0]
    unicode_list = ", ".join(f"0x{p - base:x}" for p in other)
    name = f"lv_font_inter_{weight}{size}"
    return f"""
/* {path.stem} {size}px, 8 bpp, generated by scripts/generate_kyil_ui_assets.py */
static LV_ATTRIBUTE_LARGE_CONST const uint8_t {name}_bitmap[] = {{
{c_bytes(bytes(bitmap))}
}};

static const lv_font_fmt_txt_glyph_dsc_t {name}_glyphs[] = {{
{(","+chr(10)).join(glyphs)}
}};

static const uint16_t {name}_unicode_list[] = {{ {unicode_list} }};

static const lv_font_fmt_txt_cmap_t {name}_cmaps[] = {{
    {{ .range_start = 32, .range_length = {len(ascii_points)}, .glyph_id_start = 1,
      .unicode_list = NULL, .glyph_id_ofs_list = NULL, .list_length = 0,
      .type = LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY }},
    {{ .range_start = {base}, .range_length = {other[-1] - base + 1}, .glyph_id_start = {len(ascii_points) + 1},
      .unicode_list = {name}_unicode_list, .glyph_id_ofs_list = NULL, .list_length = {len(other)},
      .type = LV_FONT_FMT_TXT_CMAP_SPARSE_TINY }},
}};

static const lv_font_fmt_txt_dsc_t {name}_dsc = {{
    .glyph_bitmap = {name}_bitmap,
    .glyph_dsc = {name}_glyphs,
    .cmaps = {name}_cmaps,
    .kern_dsc = NULL,
    .kern_scale = 0,
    .cmap_num = 2,
    .bpp = 8,
    .kern_classes = 0,
    .bitmap_format = 0,
}};

const lv_font_t {name} = {{
    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,
    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,
    .line_height = {ascent + descent},
    .base_line = {descent},
    .subpx = LV_FONT_SUBPX_NONE,
    .underline_position = -1,
    .underline_thickness = 1,
    .dsc = &{name}_dsc,
}};
"""


def hexagon(cx: float, cy: float, radius: float) -> list[tuple[float, float]]:
    """Pointy-top regular hexagon (the KyIlOS mark)."""
    return [(cx + radius * math.cos(math.radians(a)), cy + radius * math.sin(math.radians(a)))
            for a in (-90, -30, 30, 90, 150, 210)]


def draw_hex_outline(draw: ImageDraw.ImageDraw, cx: float, cy: float, radius: float, stroke: float) -> None:
    # Uniform stroke: the inner hexagon's apothem is `stroke` shorter.
    draw.polygon(hexagon(cx, cy, radius), fill=255)
    draw.polygon(hexagon(cx, cy, radius - stroke / math.cos(math.radians(30))), fill=0)


def downsample(image: Image.Image) -> Image.Image:
    return image.resize((image.width // SUPERSAMPLE, image.height // SUPERSAMPLE), Image.LANCZOS)


def hex_icon(width: int, height: int, stroke: float) -> Image.Image:
    s = SUPERSAMPLE
    image = Image.new("L", (width * s, height * s), 0)
    radius = (height * s) / 2 - s * 0.5
    draw_hex_outline(ImageDraw.Draw(image), width * s / 2, height * s / 2, radius, stroke * s)
    return downsample(image)


def wordmark(prefix: str, suffix: str, size: int) -> Image.Image:
    """Text with the hexagon standing in for an "O", as in the Figma frames."""
    s = SUPERSAMPLE
    font = ImageFont.truetype(str(FONT_PATH), size * s)
    ascent, descent = font.getmetrics()
    cap = font.getbbox("H", anchor="ls")
    cap_height = -cap[1]
    # Inter Regular's vertical stem is about 0.085 em; the ring matches it.
    stroke = size * s * 0.082
    hex_h = cap_height * 1.04
    hex_w = hex_h * math.sqrt(3) / 2
    gap = size * s * 0.035
    prefix_w = font.getlength(prefix)
    suffix_w = font.getlength(suffix)
    width = math.ceil(prefix_w + gap + hex_w + gap + suffix_w) + 4 * s
    height = ascent + descent
    image = Image.new("L", (width, height), 0)
    draw = ImageDraw.Draw(image)
    baseline = ascent
    draw.text((2 * s, baseline), prefix, font=font, fill=255, anchor="ls")
    hex_cx = 2 * s + prefix_w + gap + hex_w / 2
    hex_cy = baseline - cap_height / 2
    draw_hex_outline(draw, hex_cx, hex_cy, hex_h / 2, stroke)
    draw.text((2 * s + prefix_w + gap * 2 + hex_w, baseline), suffix, font=font, fill=255, anchor="ls")
    image = downsample(image)
    box = image.getbbox()
    return image.crop((0, box[1], image.width, box[3])) if box else image


# --- system icons ----------------------------------------------------------
# One line-art family for the whole shell: 18 px, 1.6 px strokes with round
# ends, drawn at 4x and filtered down. Suchu apps draw the same shapes
# (examples/kyil_icons.suchu), so menus and applications match.

def icon_canvas(size: int):
    s = SUPERSAMPLE
    image = Image.new("L", (size * s, size * s), 0)
    return image, ImageDraw.Draw(image), s


def stroke_line(draw, points, width, s):
    pts = [(x * s, y * s) for x, y in points]
    draw.line(pts, fill=255, width=round(width * s), joint="curve")
    r = width * s / 2
    for x, y in (pts[0], pts[-1]):
        draw.ellipse((x - r, y - r, x + r, y + r), fill=255)


def system_icon(kind: str, size: int = 18) -> Image.Image:
    image, draw, s = icon_canvas(size)
    w = 1.6
    if kind == "terminal":
        draw.rounded_rectangle((1.8 * s, 3 * s, 16.2 * s, 15 * s), radius=3 * s, outline=255, width=round(w * s))
        stroke_line(draw, [(5.2, 7), (7.6, 9), (5.2, 11)], w, s)
        stroke_line(draw, [(9.4, 11.2), (12.6, 11.2)], w, s)
    elif kind == "files":
        stroke_line(draw, [(2, 5.2), (2, 14), (16, 14), (16, 6.6), (9.2, 6.6), (7.6, 4.2), (2, 4.2), (2, 5.2)], w, s)
    elif kind == "browser":
        draw.ellipse((2 * s, 2 * s, 16 * s, 16 * s), outline=255, width=round(w * s))
        draw.ellipse((6.2 * s, 2 * s, 11.8 * s, 16 * s), outline=255, width=round(w * s))
        stroke_line(draw, [(2.6, 9), (15.4, 9)], w, s)
    elif kind == "paint":
        stroke_line(draw, [(12.5, 2.8), (15.2, 5.5), (8.2, 12.5), (5.5, 9.8), (12.5, 2.8)], w, s)
        stroke_line(draw, [(5.5, 12.5), (3, 15)], w + 0.6, s)
    elif kind == "editor":
        stroke_line(draw, [(10.5, 2.2), (4, 2.2), (4, 15.8), (14, 15.8), (14, 5.7), (10.5, 2.2), (10.5, 5.7), (14, 5.7)], w, s)
        stroke_line(draw, [(6.8, 9.4), (11.2, 9.4)], w, s)
        stroke_line(draw, [(6.8, 12.4), (11.2, 12.4)], w, s)
    elif kind == "sun":
        draw.ellipse((5.6 * s, 5.6 * s, 12.4 * s, 12.4 * s), outline=255, width=round(w * s))
        for k in range(8):
            a = math.radians(k * 45)
            stroke_line(draw, [(9 + math.cos(a) * 5.6, 9 + math.sin(a) * 5.6),
                               (9 + math.cos(a) * 7.3, 9 + math.sin(a) * 7.3)], w, s)
    elif kind == "moon":
        # Crescent: a disc with an offset disc removed, outlined by removing
        # the same shape shrunk by the stroke width.
        outer = Image.new("L", image.size, 0)
        od = ImageDraw.Draw(outer)
        od.ellipse((2.5 * s, 2.5 * s, 15.5 * s, 15.5 * s), fill=255)
        od.ellipse((6.4 * s, 0.2 * s, 18.6 * s, 12.4 * s), fill=0)
        inner = Image.new("L", image.size, 0)
        idr = ImageDraw.Draw(inner)
        t = w * s
        idr.ellipse((2.5 * s + t, 2.5 * s + t, 15.5 * s - t, 15.5 * s - t), fill=255)
        idr.ellipse((6.4 * s - t, 0.2 * s - t, 18.6 * s + t, 12.4 * s + t), fill=0)
        image = Image.composite(Image.new("L", image.size, 0), outer, inner)
    elif kind == "power":
        draw.arc((2.8 * s, 3.4 * s, 15.2 * s, 15.8 * s), start=-55, end=235, fill=255, width=round(w * s))
        stroke_line(draw, [(9, 1.8), (9, 8.4)], w, s)
    elif kind == "reboot":
        draw.arc((2.8 * s, 2.8 * s, 15.2 * s, 15.2 * s), start=20, end=320, fill=255, width=round(w * s))
        stroke_line(draw, [(15.4, 2.6), (15.4, 6.6), (11.4, 6.6)], w, s)
    return downsample(image)


def mask_c(name: str, image: Image.Image) -> str:
    return (f"const uint8_t {name}[{image.width * image.height}] = {{\n"
            f"{c_bytes(image.tobytes())}\n}};\n")


def main() -> None:
    fonts = "".join(generate_font(path, weight, size) for path, weight, size in FONTS)
    (KERNEL_SRC / "ui_font_inter.c").write_text(
        "/* Generated by scripts/generate_kyil_ui_assets.py from Inter Regular\n"
        " * (SIL Open Font License). Do not edit. */\n"
        "#include <lvgl.h>\n#include <unos/ui_fonts.h>\n" + fonts, encoding="utf-8", newline="\n")
    (KERNEL_INC / "ui_fonts.h").write_text(
        "/* Generated by scripts/generate_kyil_ui_assets.py. Do not edit. */\n"
        "#pragma once\n#include <lvgl.h>\n\n"
        "/* Inter, the system typeface of every KyIlOS surface. */\n"
        + "".join(f"LV_FONT_DECLARE(lv_font_inter_{weight}{size})\n" for _, weight, size in FONTS),
        encoding="utf-8", newline="\n")

    masks = {
        "ui_mask_hex_bar": hex_icon(25, 28, 2.0),
        "ui_mask_hex_small": hex_icon(20, 22, 1.6),
        "ui_mask_wordmark_os": wordmark("KyIl", "S", 92),
    }
    for kind in ("terminal", "files", "browser", "paint", "editor", "sun", "moon", "power", "reboot"):
        masks[f"ui_icon_{kind}"] = system_icon(kind)
    header = ["/* Generated by scripts/generate_kyil_ui_assets.py. Do not edit. */",
              "#pragma once", "#include <stdint.h>", "",
              "/* 8-bit coverage masks, coloured with the active theme when drawn. */"]
    source = ["/* Generated by scripts/generate_kyil_ui_assets.py. Do not edit. */",
              "#include <unos/ui_brand.h>", ""]
    for name, image in masks.items():
        macro = name.upper()
        header.append(f"#define {macro}_W {image.width}u")
        header.append(f"#define {macro}_H {image.height}u")
        header.append(f"extern const uint8_t {name}[{image.width * image.height}];")
        source.append(mask_c(name, image))
        image.save(ROOT / "build" / f"{name}.png")
    (KERNEL_INC / "ui_brand.h").write_text("\n".join(header) + "\n", encoding="utf-8", newline="\n")
    (KERNEL_SRC / "ui_brand_masks.c").write_text("\n".join(source), encoding="utf-8", newline="\n")
    for name, image in masks.items():
        print(f"{name}: {image.width}x{image.height}")


if __name__ == "__main__":
    main()
